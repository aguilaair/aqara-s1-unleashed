    private class Media : PermissionDelegate.MediaCallback {
        val calls = mutableListOf<String>()
        override fun grant(video: MediaSource?, audio: MediaSource?) { calls += "grant video=${video?.name} audio=${audio?.name}" }
        override fun grant(video: String?, audio: String?) { calls += "grant ids video=$video audio=$audio" }
        override fun reject() { calls += "reject" }
    }

    @Test
    fun `getUserMedia gets the microphone and the camera, else the first of each`() = harness().use { h ->
        val screen = h.mediaSource(MediaSource.SOURCE_SCREEN, "Screen")
        val camera = h.mediaSource(MediaSource.SOURCE_CAMERA, "Back camera")
        val other = h.mediaSource(MediaSource.SOURCE_OTHER, "Line in")
        val mic = h.mediaSource(MediaSource.SOURCE_MICROPHONE, "Mic")
        val m = Media()
        h.permission.onMediaPermissionRequest(h.session, dash, arrayOf(screen, camera), arrayOf(other, mic), m)
        h.permission.onMediaPermissionRequest(h.session, dash, arrayOf(screen), arrayOf(other), m)
        h.permission.onMediaPermissionRequest(h.session, dash, null, null, m)
        assertEquals(
            listOf("grant video=Back camera audio=Mic", "grant video=Screen audio=Line in", "grant video=null audio=null"),
            m.calls,
        )
        assertTrue(h.logs("S1Kiosk").contains("Granting media for $dash: audio=Mic video=Back camera"))
    }

    private class Grant : PermissionDelegate.Callback {
        val calls = mutableListOf<String>()
        override fun grant() { calls += "grant" }
        override fun reject() { calls += "reject" }
    }

    @Test
    fun `Android permissions the app already has are granted at once`() = harness().use { h ->
        shadowOf(h.app).grantPermissions(Manifest.permission.RECORD_AUDIO)
        val g = Grant()
        h.permission.onAndroidPermissionsRequest(h.session, arrayOf(Manifest.permission.RECORD_AUDIO), g)
        h.permission.onAndroidPermissionsRequest(h.session, null, g)
        assertEquals(listOf("grant", "grant"), g.calls)
    }

    @Test
    fun `while the startup permission dialog is open, Android cancels a page's request and Gecko hears no`() = harness().use { h ->
        shadowOf(h.app).denyPermissions(Manifest.permission.CAMERA, Manifest.permission.RECORD_AUDIO)
        val g = Grant()
        h.permission.onAndroidPermissionsRequest(h.session, arrayOf(Manifest.permission.CAMERA), g)
        assertEquals(2, shadowOf(h.activity).lastRequestedPermission.requestCode)
        assertEquals(listOf("reject"), g.calls)
    }

    @Test
    fun `missing Android permissions are asked for, and the answer goes back to Gecko`() = harness().use { h ->
        shadowOf(h.app).denyPermissions(Manifest.permission.CAMERA, Manifest.permission.RECORD_AUDIO)
        h.permissionDialogAnswered()
        val granted = Grant()
        h.permission.onAndroidPermissionsRequest(h.session, arrayOf(Manifest.permission.CAMERA), granted)
        val asked = shadowOf(h.activity).lastRequestedPermission
        assertEquals(2, asked.requestCode)
        assertEquals(listOf(Manifest.permission.CAMERA), asked.requestedPermissions.toList())
        h.activity.onRequestPermissionsResult(1, arrayOf(Manifest.permission.CAMERA), intArrayOf(PackageManager.PERMISSION_GRANTED))
        assertEquals(emptyList<String>(), granted.calls)
        h.activity.onRequestPermissionsResult(2, arrayOf(Manifest.permission.CAMERA), intArrayOf(PackageManager.PERMISSION_GRANTED))
        assertEquals(listOf("grant"), granted.calls)

        for (results in listOf(intArrayOf(PackageManager.PERMISSION_DENIED), intArrayOf(PackageManager.PERMISSION_GRANTED, PackageManager.PERMISSION_DENIED), intArrayOf())) {
            h.permissionDialogAnswered()
            val g = Grant()
            h.permission.onAndroidPermissionsRequest(h.session, arrayOf(Manifest.permission.CAMERA), g)
            h.activity.onRequestPermissionsResult(2, arrayOf(), results)
            assertEquals(results.toList().toString(), listOf("reject"), g.calls)
        }
    }

    @Test
    fun `a newer page request replaces one still waiting for its answer`() = harness().use { h ->
        shadowOf(h.app).denyPermissions(Manifest.permission.CAMERA, Manifest.permission.RECORD_AUDIO)
        h.permissionDialogAnswered()
        val first = Grant()
        h.permission.onAndroidPermissionsRequest(h.session, arrayOf(Manifest.permission.CAMERA), first)
        h.permissionDialogAnswered()
        val second = Grant()
        h.permission.onAndroidPermissionsRequest(h.session, arrayOf(Manifest.permission.RECORD_AUDIO), second)
        assertEquals(listOf("reject"), first.calls)
        h.activity.onRequestPermissionsResult(2, arrayOf(Manifest.permission.RECORD_AUDIO), intArrayOf(PackageManager.PERMISSION_GRANTED))
        assertEquals(listOf("grant"), second.calls)
        h.activity.onRequestPermissionsResult(2, arrayOf(Manifest.permission.RECORD_AUDIO), intArrayOf(PackageManager.PERMISSION_GRANTED))
        assertEquals(listOf("grant"), second.calls)
    }

